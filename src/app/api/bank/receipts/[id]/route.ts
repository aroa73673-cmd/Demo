import { db } from "@/lib/db";
import { requireUser } from "@/lib/auth";
import { mapError, fail } from "@/lib/api-helpers";
import { isoLabel } from "@/lib/money";
import { maskPan } from "@/lib/mask";

/**
 * Downloadable receipt. Formats: json | html.
 * The receipt is an honest artefact: it states that the record is demo data
 * and never claims a provider authorisation code that does not exist.
 */
export async function GET(req: Request, ctx: { params: Promise<{ id: string }> }) {
  try {
    const user = await requireUser();
    const { id } = await ctx.params;
    const format = new URL(req.url).searchParams.get("format") === "json" ? "json" : "html";

    const t = await db.transaction.findFirst({
      where: { id, userId: user.id },
      include: { card: { select: { label: true, last4: true, network: true } }, account: { select: { name: true } } },
    });
    if (!t) return fail(404, "Transaction not found.");

    const refund = await db.refund.findFirst({ where: { transactionId: id, status: "CONFIRMED" } });
    const receiptNo = `NB-RCPT-${t.id.slice(-8).toUpperCase()}`;

    if (format === "json") {
      return new Response(
        JSON.stringify(
          {
            receiptNo,
            environment: "NEXUS BANK sandbox — DEMO DATA, not a real financial record",
            transaction: {
              id: t.id,
              merchant: t.merchantName,
              merchantCategory: t.merchantCategory,
              amount: `${(t.amountMinor / 100).toFixed(2)} ${t.currency}`,
              status: t.status,
              method: t.method,
              orderRef: t.orderRef,
              card: t.card ? `${t.card.network} *** ${maskPan(t.card.last4)}` : null,
              account: t.account?.name,
              recordedAt: isoLabel(t.createdAt),
              postedAt: t.postedAt ? isoLabel(t.postedAt) : null,
              refundedMinor: t.refundedMinor,
              confirmedRefund: refund ? `${(refund.amountMinor / 100).toFixed(2)} ${t.currency}` : null,
            },
          },
          null,
          2,
        ),
        {
          headers: {
            "Content-Type": "application/json",
            "Content-Disposition": `attachment; filename="${receiptNo}.json"`,
          },
        },
      );
    }

    const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>Receipt ${receiptNo}</title>
<style>
  body{font-family:ui-sans-serif,system-ui,sans-serif;background:#0c0e11;color:#e7e9ea;margin:0;padding:32px 16px}
  .sheet{max-width:520px;margin:0 auto;background:#15181c;border:1px solid #2a2f36;border-radius:14px;padding:28px}
  .brand{display:flex;align-items:center;gap:10px;font-weight:700;letter-spacing:.06em}
  .logo{width:34px;height:34px;border-radius:9px;background:#0e3a2f;color:#34d399;display:flex;align-items:center;justify-content:center;font-weight:800}
  .demo{margin-top:10px;font-size:11px;color:#fbbf24;border:1px solid #fbbf2455;background:#fbbf2412;padding:6px 10px;border-radius:8px;display:inline-block}
  h1{font-size:17px;margin:18px 0 4px}
  table{width:100%;border-collapse:collapse;margin-top:14px;font-size:13px}
  td{padding:9px 0;border-bottom:1px solid #262b32;vertical-align:top}
  td:first-child{color:#9aa1a9;width:42%}
  td:last-child{text-align:right;font-variant-numeric:tabular-nums}
  .total{font-size:15px;font-weight:700}
  .foot{margin-top:18px;font-size:11px;color:#7a828b;line-height:1.5}
</style></head>
<body><div class="sheet">
  <div class="brand"><div class="logo">N</div>NEXUS BANK</div>
  <div class="demo">DEMO ENVIRONMENT — this receipt is generated from sandbox data and is not a proof of a real payment.</div>
  <h1>Purchase receipt</h1>
  <table>
    <tr><td>Receipt no.</td><td>${receiptNo}</td></tr>
    <tr><td>Merchant</td><td>${escapeHtml(t.merchantName)}</td></tr>
    ${t.merchantCategory ? `<tr><td>Merchant category</td><td>${escapeHtml(t.merchantCategory)}</td></tr>` : ""}
    ${t.orderRef ? `<tr><td>Order reference</td><td>${escapeHtml(t.orderRef)}</td></tr>` : ""}
    <tr><td>Amount</td><td class="total">${(t.amountMinor / 100).toFixed(2)} ${t.currency}</td></tr>
    <tr><td>Status</td><td>${t.status}</td></tr>
    <tr><td>Method</td><td>${t.method}</td></tr>
    ${t.card ? `<tr><td>Card</td><td>${t.card.network} ${maskPan(t.card.last4)}</td></tr>` : "<tr><td>Card</td><td>—</td></tr>"}
    <tr><td>Account</td><td>${escapeHtml(t.account?.name ?? "—")}</td></tr>
    <tr><td>Recorded</td><td>${isoLabel(t.createdAt)}</td></tr>
    ${t.postedAt ? `<tr><td>Posted</td><td>${isoLabel(t.postedAt)}</td></tr>` : ""}
    ${t.refundedMinor > 0 ? `<tr><td>Refunded</td><td>${(t.refundedMinor / 100).toFixed(2)} ${t.currency}</td></tr>` : ""}
  </table>
  <p class="foot">Generated by NEXUS BANK demo environment. No payment network, issuer or merchant system was contacted. Amounts and statuses were declared inside the sandbox and are labelled demo data throughout the product.</p>
</div></body></html>`;

    return new Response(html, {
      headers: {
        "Content-Type": "text/html; charset=utf-8",
        "Content-Disposition": `inline; filename="${receiptNo}.html"`,
      },
    });
  } catch (err) {
    return mapError(err);
  }
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c] as string));
}
